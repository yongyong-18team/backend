-- ERD v1.4 MVP 전체 스키마. 이미 머지된 뒤에는 고치지 말고 새 마이그레이션을 추가한다.
-- enum 값은 VARCHAR로 두고 검증은 애플리케이션 enum이 한다(ERD 1장).

-- 3-1. 계정·권한 ------------------------------------------------------------

CREATE TABLE users (
    user_id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id               VARCHAR(20)  NOT NULL UNIQUE,
    password_hash          VARCHAR(100) NOT NULL,
    display_name           VARCHAR(30),
    relation               VARCHAR(10),
    last_burnout_notice_at TIMESTAMPTZ,
    created_at             TIMESTAMPTZ  NOT NULL,
    updated_at             TIMESTAMPTZ  NOT NULL
);

CREATE TABLE care_subject (
    subject_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id     BIGINT      NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    name              VARCHAR(20) NOT NULL CHECK (char_length(name) BETWEEN 2 AND 20),
    -- 현재 연도 상한은 INSERT·UPDATE 시점에만 검사된다
    birth_year        SMALLINT    NOT NULL CHECK (birth_year >= 1930 AND birth_year <= EXTRACT(YEAR FROM CURRENT_DATE)),
    district          VARCHAR(10) NOT NULL,
    dong              VARCHAR(20),
    emergency_contact VARCHAR(100),
    created_at        TIMESTAMPTZ NOT NULL,
    updated_at        TIMESTAMPTZ NOT NULL
);

CREATE TABLE consent (
    consent_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT      NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    subject_id    BIGINT      NOT NULL REFERENCES care_subject (subject_id) ON DELETE CASCADE,
    consent_type  VARCHAR(30) NOT NULL,
    terms_version VARCHAR(10) NOT NULL,
    agreed_at     TIMESTAMPTZ NOT NULL,
    UNIQUE (user_id, subject_id, consent_type, terms_version)
);

CREATE TABLE invitation (
    invitation_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id      BIGINT      NOT NULL REFERENCES care_subject (subject_id) ON DELETE CASCADE,
    invitee_user_id BIGINT      NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    status          VARCHAR(10) NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL,
    responded_at    TIMESTAMPTZ
);

CREATE UNIQUE INDEX uq_invitation_pending
    ON invitation (subject_id, invitee_user_id) WHERE status = 'PENDING';

CREATE TABLE co_manager (
    subject_id    BIGINT      NOT NULL REFERENCES care_subject (subject_id) ON DELETE CASCADE,
    user_id       BIGINT      NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    invitation_id BIGINT      NOT NULL UNIQUE REFERENCES invitation (invitation_id),
    activated_at  TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (subject_id, user_id)
);

-- 3-2. 기록·설명서 ----------------------------------------------------------

CREATE TABLE diary (
    diary_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id      BIGINT      NOT NULL REFERENCES care_subject (subject_id) ON DELETE CASCADE,
    diary_date      DATE        NOT NULL,
    content         TEXT        NOT NULL,
    input_type      VARCHAR(10) NOT NULL,
    analysis_status VARCHAR(12) NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_diary_subject_date ON diary (subject_id, diary_date);

CREATE TABLE ai_analysis (
    diary_id       BIGINT       NOT NULL REFERENCES diary (diary_id) ON DELETE CASCADE,
    analysis_no    SMALLINT     NOT NULL,
    safety_level   VARCHAR(10)  NOT NULL,
    empathy_text   VARCHAR(300),
    raw_json       JSONB,
    prompt_version VARCHAR(20)  NOT NULL,
    model_name     VARCHAR(50),
    created_at     TIMESTAMPTZ  NOT NULL,
    PRIMARY KEY (diary_id, analysis_no),
    CONSTRAINT ck_ai_analysis_crisis_no_empathy CHECK (safety_level <> 'CRISIS' OR empathy_text IS NULL)
);

CREATE TABLE extracted_item (
    diary_id       BIGINT       NOT NULL REFERENCES diary (diary_id) ON DELETE CASCADE,
    item_no        SMALLINT     NOT NULL,
    category       VARCHAR(20)  NOT NULL,
    label          VARCHAR(30),
    content        VARCHAR(500) NOT NULL,
    time_slot      VARCHAR(10),
    duration_min   SMALLINT,
    episode_no     SMALLINT,
    evidence_quote VARCHAR(500) NOT NULL,
    status         VARCHAR(10)  NOT NULL,
    edited         BOOLEAN      NOT NULL DEFAULT false,
    PRIMARY KEY (diary_id, item_no)
);

CREATE TABLE guide_entry (
    entry_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id        BIGINT       NOT NULL REFERENCES care_subject (subject_id) ON DELETE CASCADE,
    section           VARCHAR(20)  NOT NULL,
    content           VARCHAR(500) NOT NULL,
    source_type       VARCHAR(12)  NOT NULL,
    src_diary_id      BIGINT,
    src_item_no       SMALLINT,
    src_question_code VARCHAR(5),
    created_at        TIMESTAMPTZ  NOT NULL,
    updated_at        TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_guide_entry_src_item FOREIGN KEY (src_diary_id, src_item_no)
        REFERENCES extracted_item (diary_id, item_no) ON DELETE SET NULL,
    CONSTRAINT uq_guide_entry_src_item UNIQUE (src_diary_id, src_item_no)
);

CREATE INDEX idx_guide_entry_subject_section ON guide_entry (subject_id, section);

-- 3-3. 공유 -----------------------------------------------------------------

CREATE TABLE share (
    share_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id             BIGINT      NOT NULL REFERENCES care_subject (subject_id) ON DELETE CASCADE,
    created_by             BIGINT      REFERENCES users (user_id) ON DELETE SET NULL,
    document_type          VARCHAR(10) NOT NULL,
    recipient_label        VARCHAR(30),
    source_diary_id        BIGINT      REFERENCES diary (diary_id) ON DELETE SET NULL,
    period_start           DATE,
    show_emergency_contact BOOLEAN     NOT NULL DEFAULT false,
    snapshot_json          JSONB,
    valid_days             SMALLINT    NOT NULL DEFAULT 7,
    token_hash             CHAR(64)    UNIQUE,
    approved_at            TIMESTAMPTZ,
    expires_at             TIMESTAMPTZ,
    revoked_at             TIMESTAMPTZ,
    created_at             TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_share_valid_days CHECK (valid_days = 7),
    CONSTRAINT ck_share_weekly_period CHECK (document_type <> 'WEEKLY' OR period_start IS NOT NULL),
    CONSTRAINT ck_share_approved_token CHECK ((approved_at IS NULL) = (token_hash IS NULL))
);

CREATE TABLE share_section (
    share_id     BIGINT      NOT NULL REFERENCES share (share_id) ON DELETE CASCADE,
    section_code VARCHAR(30) NOT NULL,
    PRIMARY KEY (share_id, section_code)
);

-- 3-4. 돌봄 지원 ------------------------------------------------------------

CREATE TABLE resource (
    resource_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_kind VARCHAR(10)  NOT NULL,
    name          VARCHAR(100) NOT NULL,
    phone         VARCHAR(20),
    official_url  VARCHAR(300)
);

CREATE TABLE facility (
    resource_id   BIGINT       PRIMARY KEY REFERENCES resource (resource_id) ON DELETE CASCADE,
    source        VARCHAR(20)  NOT NULL,
    external_id   VARCHAR(50)  NOT NULL,
    facility_type VARCHAR(50)  NOT NULL,
    district      VARCHAR(10)  NOT NULL,
    address       VARCHAR(200),
    lat           NUMERIC(9, 6),
    lng           NUMERIC(9, 6),
    services      TEXT,
    fetched_at    TIMESTAMPTZ  NOT NULL,
    UNIQUE (source, external_id)
);

CREATE INDEX idx_facility_type_district ON facility (facility_type, district);

CREATE TABLE support_program (
    resource_id         BIGINT      PRIMARY KEY REFERENCES resource (resource_id) ON DELETE CASCADE,
    program_type        VARCHAR(30) NOT NULL,
    care_term           VARCHAR(10) NOT NULL,
    summary             TEXT,
    eligibility_summary TEXT,
    target_conditions   JSONB       NOT NULL,
    procedure           TEXT,
    source_doc          VARCHAR(200),
    doc_version         VARCHAR(20)
);

CREATE TABLE program_facility_type (
    program_id    BIGINT      NOT NULL REFERENCES support_program (resource_id) ON DELETE CASCADE,
    facility_type VARCHAR(50) NOT NULL,
    PRIMARY KEY (program_id, facility_type)
);

CREATE TABLE wellbeing_signal (
    signal_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT      NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    diary_id      BIGINT      REFERENCES diary (diary_id) ON DELETE SET NULL,
    signal_type   VARCHAR(10) NOT NULL,
    detected_date DATE        NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL,
    UNIQUE (user_id, signal_type, detected_date)
);
